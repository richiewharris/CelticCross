#!/usr/bin/env python3
"""Builds the game's insights file (src/games/roth/engine/insights.json) from the cube.

What the game reads from it now: how well each deck does as the second player at each setting, against each first
player's deck, measured by a settings sweep (one run per setting, the setting fixed by the rules):

  for s in ford tower bog crossing brugh loughs emain cruachan; do
    npx tsx sim/roth/balance.ts --n 40 --workers 2 --rules "{\"setting\":\"$s\"}"; done
  python3 sim/roth/cube/digest.py

Each matchup cell has only ~20 matches per setting, so it is pulled toward the deck's score at that setting against
the whole field (a shrinkage of k matches' weight). The file also keeps the settings as they were when measured; the
game ignores the scores if the settings have changed since (and falls back to its own estimate).

Usage: python3 sim/roth/cube/digest.py [--k 20] [--out src/games/roth/engine/insights.json]
"""
import json
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cube  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
REACT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))


def main():
    args = sys.argv[1:]
    k = float(args[args.index("--k") + 1]) if "--k" in args else 20.0
    out = args[args.index("--out") + 1] if "--out" in args else os.path.join(REACT, "src/games/roth/engine/insights.json")
    # the latest run for each fixed setting
    sweep = {}
    for m in cube.metas():
        s = (m.get("rules") or {}).get("setting")
        if s and not m.get("base") and set(m["rules"]) == {"setting"}:
            sweep[s] = m
    if not sweep:
        sys.exit("no settings sweep in the cube (see the usage above)")
    scores = {}  # p2 deck -> p1 deck -> setting -> score
    for s, m in sorted(sweep.items()):
        _, db = cube.load(m["id"])
        cells = db.execute("SELECT deck, foe, avg(score), count(*) FROM sides WHERE seat = 2 AND deck <> foe GROUP BY deck, foe").fetchall()
        field = {d: v for d, v in db.execute("SELECT deck, avg(score) FROM sides WHERE seat = 2 AND deck <> foe GROUP BY deck").fetchall()}
        for deck, foe, v, n in cells:
            est = (n * v + k * field[deck]) / (n + k)
            scores.setdefault(deck, {}).setdefault(foe, {})[s] = round(est, 3)
    settings = json.loads(subprocess.check_output(
        ["npx", "tsx", "-e", 'import { SETTINGS } from "./src/games/roth/engine/settings"; console.log(JSON.stringify(SETTINGS))'],
        cwd=REACT, text=True))
    doc = {
        "note": "Generated by sim/roth/cube/digest.py from the balance cube. Don't edit by hand.",
        "runs": {s: m["id"] for s, m in sorted(sweep.items())},
        "engines": sorted({m["engine"] for m in sweep.values()}),
        "settings": settings,
        "secondPlayer": scores,
    }
    with open(out, "w") as fh:
        json.dump(doc, fh, indent=1, sort_keys=True)
        fh.write("\n")
    print(f"wrote {out}: {len(sweep)} settings, from runs {', '.join(m['id'] for m in sweep.values())}")
    # what the computer will now choose, and what the old estimate chose
    print("\nThe second player's best setting by the sweep (score), per first player's deck:")
    for d in sorted(scores):
        print(f"  {d:9} " + ", ".join(f"vs {f} {max(v, key=v.get)} {100 * max(v.values()):.0f}%" for f, v in sorted(scores[d].items())))


if __name__ == "__main__":
    main()
